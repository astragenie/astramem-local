/**
 * shim.ts — stable launcher shim for the Windows service (D1).
 *
 * The scheduled task points FOREVER at a stable path:
 *   %LOCALAPPDATA%\Astramem\bin\astramemd.cmd
 * which runs
 *   %LOCALAPPDATA%\Astramem\bin\launch.cjs
 * which reads
 *   %LOCALAPPDATA%\Astramem\bin\current.json   { nodeBin, entryJs, port }
 * and spawns the daemon.
 *
 * Upgrades rewrite current.json only — schtasks is never touched again, so
 * the one failure mode that requires elevation (task registration) can only
 * occur once, at first install. This also kills the stale-baked-path bug
 * where the task kept launching whichever build happened to run
 * `service install`.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

export interface ShimPointer {
  nodeBin: string;
  entryJs: string;
  port: number;
}

export interface ShimPaths {
  binDir: string;
  cmdPath: string;
  launcherPath: string;
  pointerPath: string;
}

/** Stable bin dir: <localAppData>\Astramem\bin (same root as the data dir). */
export function shimPaths(localAppData?: string): ShimPaths {
  const base = localAppData ?? process.env['LOCALAPPDATA'] ?? '';
  const binDir = join(base, 'Astramem', 'bin');
  return {
    binDir,
    cmdPath: join(binDir, 'astramemd.cmd'),
    launcherPath: join(binDir, 'launch.cjs'),
    pointerPath: join(binDir, 'current.json'),
  };
}

/**
 * launch.cjs — plain CommonJS so the shim works with any Node the pointer
 * names, regardless of the package's ESM setup. Kept dependency-free.
 *
 * Uses spawnSync (not detached spawn): the scheduled task's own process
 * lifetime then matches the daemon's, so Task Scheduler status reflects
 * reality and `schtasks /end` can actually stop the daemon.
 */
const LAUNCHER_SOURCE = `// astramem-local service launcher — generated by 'service install' / 'reinstall'.
// Reads current.json (written on every install/upgrade) and runs the daemon.
'use strict';
const { readFileSync } = require('node:fs');
const { spawnSync } = require('node:child_process');
const { join } = require('node:path');

const pointerPath = join(__dirname, 'current.json');
let ptr;
try {
  ptr = JSON.parse(readFileSync(pointerPath, 'utf8'));
} catch (err) {
  console.error('[astramemd-shim] cannot read ' + pointerPath + ': ' + err.message);
  console.error('[astramemd-shim] run: astramem-local reinstall');
  process.exit(1);
}
if (!ptr.nodeBin || !ptr.entryJs) {
  console.error('[astramemd-shim] current.json missing nodeBin/entryJs — run: astramem-local reinstall');
  process.exit(1);
}
const args = [ptr.entryJs, 'serve', '--port', String(ptr.port || 7777)];
const res = spawnSync(ptr.nodeBin, args, { stdio: 'inherit' });
process.exit(res.status === null ? 1 : res.status);
`;

/**
 * Write (or overwrite) the stable shim trio. Idempotent — we own the whole
 * file contents, so a plain overwrite is safe and self-healing.
 */
export function writeShim(pointer: ShimPointer, paths: ShimPaths = shimPaths()): ShimPaths {
  mkdirSync(paths.binDir, { recursive: true });
  // The cmd resolves node from the pointer at run time via launch.cjs; the
  // cmd itself only needs SOME node on PATH-less systems, so it uses the
  // pointer's nodeBin directly to run the launcher too.
  const cmd = `@echo off\r\n"${pointer.nodeBin}" "${paths.launcherPath}"\r\n`;
  writeFileSync(paths.cmdPath, cmd, 'utf8');
  writeFileSync(paths.launcherPath, LAUNCHER_SOURCE, 'utf8');
  writeFileSync(paths.pointerPath, JSON.stringify(pointer, null, 2) + '\n', 'utf8');
  return paths;
}
